/**
 * Generate 4 Multiple Choice (A, B, C, D) options with shuffled answer
 */
export function buildMultipleChoiceQuestion(
  item: MultilingualSeedItem,
  questionType: string = 'VOCABULARY_QUIZ',
): GameQuestionPayload {
  const letters = ['A', 'B', 'C', 'D'];
  const isTargetPrompt = questionType === 'VOCABULARY_QUIZ' || questionType === 'WORD_MATCHING';

  // For Vocabulary Quiz: Question displays Target Word (Japanese, Korean, etc.), options are Vietnamese meanings
  // For Word Recognition / Spelling: Question displays definition / Vietnamese, options are in Target language
  const correctAnswer = isTargetPrompt ? item.meaningVi : item.targetWord;
  const rawDistractors = isTargetPrompt
    ? [...item.distractorsVi]
    : [...(item.distractorsTarget || item.distractorsVi)];

  // Shuffle distractors and pick 3
  const shuffledDistractors = rawDistractors.sort(() => Math.random() - 0.5).slice(0, 3);
  const correctIndex = Math.floor(Math.random() * 4); // 0, 1, 2, or 3

  const optionTexts: string[] = [];
  let dIdx = 0;
  for (let i = 0; i < 4; i++) {
    if (i === correctIndex) {
      optionTexts.push(correctAnswer);
    } else {
      const fallback = rawDistractors[dIdx] || (isTargetPrompt ? `Nghĩa khác ${letters[i]}` : `Phương án ${letters[i]}`);
      optionTexts.push(shuffledDistractors[dIdx] || fallback);
      dIdx++;
    }
  }

  // Pre-formatted option strings e.g. ["A. Xin chào", "B. Cảm ơn", "C. ...", "D. ..."]
  const optionsWithLetters = optionTexts.map((opt, idx) => `${letters[idx]}. ${opt}`);
  const acceptedAnswers = [
    letters[correctIndex], // "A" / "B" / "C" / "D"
    letters[correctIndex].toLowerCase(),
    correctAnswer.toLowerCase().trim(),
    `${letters[correctIndex]}. ${correctAnswer}`.toLowerCase().trim(),
  ];
  if (item.phonetic) {
    acceptedAnswers.push(item.phonetic.toLowerCase().trim());
  }

  let promptText = '';
  if (isTargetPrompt) {
    promptText = `Chọn nghĩa đúng của từ「${item.targetWord}」${item.phonetic ? ` (${item.phonetic})` : ''}:`;
  } else if (questionType === 'LISTENING_CHALLENGE') {
    promptText = '🎧 Hãy lắng nghe phát âm và chọn đáp án chính xác:';
  } else if (questionType === 'MISSING_WORD' && item.exampleSentence) {
    const escaped = item.targetWord.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
    const wordRegex = new RegExp(`\\b${escaped}\\b`, 'i');
    const fallbackRegex = new RegExp(escaped, 'i');
    const blankSentence = wordRegex.test(item.exampleSentence)
      ? item.exampleSentence.replace(wordRegex, '______')
      : item.exampleSentence.replace(fallbackRegex, '______');
    promptText = `Điền từ thích hợp vào chỗ trống: "${blankSentence}"`;
  } else {
    promptText = `Từ nào tương ứng với nghĩa: "${item.meaningVi}"?`;
  }

  const hint = item.exampleSentence
    ? `Ngữ cảnh: ${item.exampleSentence.replace(new RegExp(item.targetWord.replace(/[.*+?^${}()|[\]\\]/g, '\\$&'), 'i'), '______')}`
    : item.partOfSpeech
    ? `Từ loại: ${item.partOfSpeech}`
    : undefined;

  return {
    id: item.id,
    prompt: promptText,
    direction: isTargetPrompt ? 'TARGET_VI' : 'VI_TARGET',
    correctAnswer: letters[correctIndex], // Server matches A/B/C/D or full text
    acceptedAnswers,
    options: optionsWithLetters,
    correctOptionIndex: correctIndex,
    explanation: `${item.targetWord}${item.phonetic ? ` [${item.phonetic}]` : ''} (${item.partOfSpeech || 'từ vựng'}): ${item.meaningVi}.${item.exampleSentence ? ` Ví dụ: ${item.exampleSentence} (${item.exampleTranslation || ''})` : ''}`,
    difficulty: 3.0,
    category: item.category,
    languageCode: item.languageCode,
    questionType,
    phonetic: item.phonetic,
    targetWord: item.targetWord,
    hint,
  };
}
